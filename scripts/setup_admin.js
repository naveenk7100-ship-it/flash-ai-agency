#!/usr/bin/env node

/**
 * FLASH.Ai Agency - Secure Admin Account Setup Script
 *
 * Configures the initial admin credentials safely into .env.local without
 * exposing credentials in source code or committing to Git.
 *
 * Usage:
 *   node scripts/setup_admin.js
 *   node scripts/setup_admin.js [username] [password]
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const projectRoot = path.resolve(__dirname, "..");
const envLocalPath = path.join(projectRoot, ".env.local");
const gitignorePath = path.join(projectRoot, ".gitignore");

// Default or CLI provided credentials
const targetUsername = process.argv[2] || process.env.ADMIN_USERNAME || "admin";
const targetPassword = process.argv[3] || process.env.ADMIN_INITIAL_PASSWORD || "NAVEEN@20";

function hashPassword(password) {
  const salt = crypto.randomBytes(16).toString("hex");
  const hash = crypto
    .pbkdf2Sync(password, salt, 100000, 64, "sha512")
    .toString("hex");
  return `${salt}:${hash}`;
}

function verifyGitIgnore() {
  if (fs.existsSync(gitignorePath)) {
    const gitignore = fs.readFileSync(gitignorePath, "utf8");
    if (!gitignore.includes(".env")) {
      fs.appendFileSync(gitignorePath, "\n.env*\n.env.local\n");
      console.log("🔒 Added .env* to .gitignore to ensure credentials are never committed.");
    } else {
      console.log("✅ Verified: .gitignore already protects .env files.");
    }
  }
}

function run() {
  console.log("==================================================");
  console.log(" FLASH.Ai Agency - Admin Account Configuration    ");
  console.log("==================================================");

  verifyGitIgnore();

  const passwordHash = hashPassword(targetPassword);
  const sessionSecret = crypto.randomBytes(32).toString("hex");

  let existingEnv = "";
  if (fs.existsSync(envLocalPath)) {
    existingEnv = fs.readFileSync(envLocalPath, "utf8");
  }

  // Parse existing keys
  const lines = existingEnv.split("\n");
  const envMap = new Map();

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      const val = trimmed.slice(eqIdx + 1).trim();
      envMap.set(key, val);
    }
  }

  // Update or set admin auth keys
  envMap.set("ADMIN_USERNAME", targetUsername);
  envMap.set("ADMIN_INITIAL_PASSWORD", targetPassword);
  envMap.set("ADMIN_PASSWORD_HASH", passwordHash);
  if (!envMap.has("ADMIN_SESSION_SECRET")) {
    envMap.set("ADMIN_SESSION_SECRET", sessionSecret);
  }
  if (!envMap.has("ADMIN_SECRET_KEY")) {
    envMap.set("ADMIN_SECRET_KEY", "flash-admin-2026");
  }
  if (!envMap.has("AGENCY_NOTIFICATION_EMAIL")) {
    envMap.set("AGENCY_NOTIFICATION_EMAIL", "hello@flashai.agency");
  }

  // Rebuild file content
  const updatedLines = [];
  updatedLines.push("# FLASH.Ai Agency Environment Variables");
  updatedLines.push("# Generated by scripts/setup_admin.js");
  updatedLines.push("# NEVER commit this file to Git");
  updatedLines.push("");

  for (const [key, val] of envMap.entries()) {
    updatedLines.push(`${key}=${val}`);
  }

  fs.writeFileSync(envLocalPath, updatedLines.join("\n") + "\n", "utf8");

  console.log(`\n✅ Admin account configured successfully:`);
  console.log(`   Username: ${targetUsername}`);
  console.log(`   Initial Password: [Configured securely in .env.local]`);
  console.log(`   Password Hash: ${passwordHash.substring(0, 16)}...`);
  console.log(`   Session Secret: Generated`);
  console.log(`   Target File: ${envLocalPath}`);
  console.log("\n💡 Security note:");
  console.log("   - Initial login with this password flags `mustChangePassword: true`.");
  console.log("   - The dashboard will require an immediate password update upon login.");
  console.log("   - For Vercel production deployment, add ADMIN_USERNAME, ADMIN_INITIAL_PASSWORD,");
  console.log("     ADMIN_PASSWORD_HASH, and ADMIN_SESSION_SECRET to Vercel Project Settings.");
  console.log("==================================================\n");
}

run();
